// 把字典裡的「{name}」換成角色現在的名字：字串直接換，陣列逐項換，
// 函式（例如 daysTogether(n)）包一層、把回傳的字串再換一次，巢狀物件（settings、diary）遞迴處理。
function fillName(value, name) {
  if (typeof value === 'string') return value.split('{name}').join(name);
  if (typeof value === 'function') return (...args) => fillName(value(...args), name);
  if (Array.isArray(value)) return value.map((v) => fillName(v, name));
  if (value && typeof value === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(value)) out[k] = fillName(v, name);
    return out;
  }
  return value;
}

/**
 * @param {string} lang 'zh' | 'ja'
 * @param {string} [companionName] 使用者在設定面板取的名字；空的話用這個語言的 defaultName
 */
export function getStrings(lang, companionName = '') {
  const dict = STRINGS[lang] || STRINGS.zh;
  const name = (companionName || '').trim() || dict.defaultName;
  return fillName(dict, name);
}
